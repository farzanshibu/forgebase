import { it, vi } from "vitest";
import { screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MockApi } from "../../test/mockApi";
import { renderStudio, signedIn } from "../../test/helpers";
import { addJsFunction, installFunctions } from "../../test/fnMock";
import { monacoState } from "../../test/monacoMock";
vi.mock("./monacoEnv", async () => (await import("../../test/monacoMock")).monacoEnvMock());
it("dbg", async () => {
  monacoState.reset();
  const mock = signedIn(new MockApi().install());
  addJsFunction(installFunctions(mock));
  renderStudio("/functions/new");
  const form = await screen.findByRole("form", { name: "Function settings" });
  const nameBox = within(form).getByLabelText(/^Name/);
  await userEvent.clear(nameBox);
  await userEvent.type(nameBox, "typed");
  await new Promise((r) => setTimeout(r, 1500));
  throw new Error("LABELS " + JSON.stringify([screen.queryAllByRole("textbox").map((e) => e.getAttribute("aria-label") + "|" + (e as HTMLInputElement).value.slice(0, 20)), mock.problems]) + " TEXT " + document.body.textContent?.slice(0, 1200));
});
