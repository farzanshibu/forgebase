/** Plain helpers of the PostgreSQL pages (kept out of the component files so fast refresh works). */
import { listCollections, listServiceAccounts, searchUsers, type DbLogin } from "../../api";
import { runSqlStatement, type RunAs } from "./sqlRequest";

export interface PolicyRow {
  schema: string;
  table: string;
  name: string;
  /** `PERMISSIVE` or `RESTRICTIVE`. */
  mode: string;
  command: string;
  roles: string;
  using: string;
  check: string;
}

export const POLICIES_SQL =
  "SELECT schemaname, tablename, policyname, permissive, cmd, roles::text, qual, with_check FROM pg_catalog.pg_policies " +
  "WHERE schemaname NOT IN ('pg_catalog', 'information_schema') ORDER BY schemaname, tablename, policyname";

/** Generated by ForgeBase: `fb_*` on a `public` table (ADR-0028 addendum FB-153). */
export const isGenerated = (p: Pick<PolicyRow, "schema" | "name">) => p.schema === "public" && p.name.startsWith("fb_");
/** A hand-written policy that widens what direct logins see. */
export const widens = (p: PolicyRow) => !isGenerated(p) && p.mode.toUpperCase() === "PERMISSIVE";

export async function loadPolicies(): Promise<PolicyRow[]> {
  const r = await runSqlStatement(POLICIES_SQL);
  const at = (name: string) => r.columns.indexOf(name);
  const s = (row: unknown[], name: string) => {
    const v = row[at(name)];
    return v === null || v === undefined ? "" : String(v);
  };
  return r.rows.map((row) => ({
    schema: s(row, "schemaname"), table: s(row, "tablename"), name: s(row, "policyname"), mode: s(row, "permissive"),
    command: s(row, "cmd"), roles: s(row, "roles"), using: s(row, "qual"), check: s(row, "with_check"),
  }));
}


/** What a login can do, in plain words. */
export function accessWords(l: Pick<DbLogin, "admin" | "readonly">): string {
  return l.admin ? "Administrator (SQL editor rights)" : l.readonly ? "Read only" : "Read and write";
}

/** The login sees nothing: its principal or tenant is gone. Admin logins have no claims by design. */
export const seesNothing = (l: Pick<DbLogin, "admin" | "has_claims">) => !l.admin && !l.has_claims;


/** Who manages an extension, in plain words. */
export function managedWords(by: string): string {
  if (by === "api") return "You (here)";
  if (by === "schema") return "ForgeBase schema";
  if (by.startsWith("feature:")) return `Feature: ${by.slice("feature:".length)}`;
  return by;
}


export const ADMIN = "";
const TENANTS_KEY = "forgebase.sql.tenants";

export interface Principal { key: string; label: string }

/** Users of every auth collection (first 50 each) and the service accounts. */
export async function loadPrincipals(signal?: AbortSignal): Promise<Principal[]> {
  const out: Principal[] = [];
  const collections = (await listCollections(signal)).filter((c) => c.type === "auth");
  for (const c of collections) {
    try {
      const page = await searchUsers(c.name, { per_page: 50 }, signal);
      for (const r of page.items) out.push({ key: `user:${c.name}/${String(r.id)}`, label: `${String(r.email ?? r.username ?? r.id)} (user in ${c.name})` });
    } catch {
      // A collection the caller cannot list is skipped: the rest of the picker still works.
    }
  }
  try {
    for (const s of await listServiceAccounts(signal)) out.push({ key: `service:${s.id}`, label: `${s.name} (service account)` });
  } catch {
    // No permission to list service accounts: users still work.
  }
  return out;
}

export function rememberedTenants(): string[] {
  try {
    const v: unknown = JSON.parse(localStorage.getItem(TENANTS_KEY) ?? "[]");
    return Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : [];
  } catch {
    return [];
  }
}
export function rememberTenant(t: string) {
  if (!t) return;
  try {
    localStorage.setItem(TENANTS_KEY, JSON.stringify([t, ...rememberedTenants().filter((x) => x !== t)].slice(0, 10)));
  } catch {
    // Storage may be off (private window): the tenant is just not remembered.
  }
}


export const toRunAs = (principal: string, tenant: string): RunAs | undefined => (principal === ADMIN ? undefined : { principal, ...(tenant.trim() ? { tenant: tenant.trim() } : {}) });
