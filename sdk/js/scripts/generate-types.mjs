#!/usr/bin/env node
// Regenerates src/generated/openapi.ts from the server's OpenAPI document.
//
//   npm run generate                         # from openapi/openapi.json
//   npm run generate -- --url http://127.0.0.1:8080   # fetch /api/openapi.json first (refreshes the checked-in copy)
//   npm run generate -- --file path/to/openapi.json
//   npm run generate:check                   # fail when the checked-in types are stale (CI)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (n) => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : undefined;
};
const check = args.includes("--check");
const docPath = resolve(root, flag("--file") ?? "openapi/openapi.json");
const url = flag("--url");

if (url) {
  const res = await fetch(`${url.replace(/\/+$/, "")}/api/openapi.json`);
  if (!res.ok) throw new Error(`GET /api/openapi.json -> ${res.status}`);
  const doc = await res.json();
  writeFileSync(resolve(root, "openapi/openapi.json"), `${JSON.stringify(doc, null, 2)}\n`);
}

const doc = JSON.parse(readFileSync(url ? resolve(root, "openapi/openapi.json") : docPath, "utf8"));
// The server reuses short operationIds across routes (`list`, `stats`, ...), which the generator
// rejects. Make the repeated ones unique by prefixing the HTTP method and path.
const seen = new Map();
for (const item of Object.values(doc.paths)) for (const op of Object.values(item)) if (op?.operationId) seen.set(op.operationId, (seen.get(op.operationId) ?? 0) + 1);
for (const [path, item] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (op?.operationId && seen.get(op.operationId) > 1) {
      op.operationId = `${method}_${path.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "")}`;
    }
  }
}
const ast = await openapiTS(doc, { alphabetize: true });
const out = `// Generated by scripts/generate-types.mjs from openapi/openapi.json. Do not edit.\n/* eslint-disable */\n${astToString(ast)}`;
const target = resolve(root, "src/generated/openapi.ts");

if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* missing */
  }
  if (current !== out) {
    console.error("src/generated/openapi.ts is stale: run `npm run generate` and commit the result.");
    process.exit(1);
  }
  console.log("generated types are up to date");
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
