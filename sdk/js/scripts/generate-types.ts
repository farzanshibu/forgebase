#!/usr/bin/env node
// Regenerates src/generated/openapi.ts from the server's OpenAPI document. TypeScript run directly by Node
// (22.18 or later strips the types itself), so there is nothing to compile first.
//
//   npm run generate                         # from openapi/openapi.json
//   npm run generate -- --url http://127.0.0.1:8080   # fetch /api/openapi.json first (refreshes the checked-in copy)
//   npm run generate -- --file path/to/openapi.json
//   npm run generate:check                   # fail when the checked-in types are stale (CI)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (n: string): string | undefined => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : undefined;
};
const check = args.includes("--check");
const docPath = resolve(root, flag("--file") ?? "openapi/openapi.json");
const url = flag("--url");

/** The checked-in format (shared with sdk/rust/openapi): compact, object keys sorted, one trailing newline. */
const canonical = (v: unknown): unknown =>
  Array.isArray(v)
    ? v.map(canonical)
    : v !== null && typeof v === "object"
      ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, canonical((v as Record<string, unknown>)[k])]))
      : v;

if (url) {
  const res = await fetch(`${url.replace(/\/+$/, "")}/api/openapi.json`);
  if (!res.ok) throw new Error(`GET /api/openapi.json -> ${res.status}`);
  const doc: unknown = await res.json();
  writeFileSync(resolve(root, "openapi/openapi.json"), `${JSON.stringify(canonical(doc))}\n`);
}

const doc = JSON.parse(readFileSync(url ? resolve(root, "openapi/openapi.json") : docPath, "utf8")) as Parameters<typeof openapiTS>[0];
const ast = await openapiTS(doc, { alphabetize: true });
const out = `// Generated by scripts/generate-types.ts from openapi/openapi.json. Do not edit.\n/* eslint-disable */\n${astToString(ast)}`;
const target = resolve(root, "src/generated/openapi.ts");

if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* missing */
  }
  if (current !== out) {
    console.error("src/generated/openapi.ts is stale: run `npm run generate` and commit the result.");
    process.exit(1);
  }
  console.log("generated types are up to date");
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
