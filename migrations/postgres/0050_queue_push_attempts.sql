-- PostgreSQL twin of migrations/system/0050_queue_push_attempts.sql
-- (ADR-0031 §1): the delivery attempt log of push subscriptions.

CREATE TABLE _forgebase_queue_push_attempts (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription       text   NOT NULL REFERENCES _forgebase_queue_subscriptions (name) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    message_id         text   NOT NULL,
    attempt            bigint NOT NULL,
    test               bigint NOT NULL DEFAULT 0,
    kind               text   NOT NULL,
    endpoint           text   NOT NULL,
    at                 bigint NOT NULL,
    latency_ms         bigint NOT NULL,
    outcome            text   NOT NULL CHECK (outcome IN ('success', 'failure')),
    status             bigint,
    error_class        text,
    error              text,
    request_headers    text   NOT NULL DEFAULT '{}',
    response_headers   text   NOT NULL DEFAULT '{}',
    response_body      text,
    response_bytes     bigint,
    response_truncated bigint NOT NULL DEFAULT 0
);

CREATE INDEX _forgebase_queue_push_attempts_sub ON _forgebase_queue_push_attempts (subscription, id);
CREATE INDEX _forgebase_queue_push_attempts_message ON _forgebase_queue_push_attempts (subscription, message_id);
CREATE INDEX _forgebase_queue_push_attempts_at ON _forgebase_queue_push_attempts (at);
