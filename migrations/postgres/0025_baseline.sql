-- Lines of a finalized invoice are immutable (0020_billing). A trigger's WHEN
-- cannot hold a subquery on PostgreSQL, so the function checks the invoice.
CREATE FUNCTION forgebase._forgebase_billing_lines_frozen() RETURNS trigger
LANGUAGE plpgsql AS $fb$
DECLARE
    invoice text;
BEGIN
    IF TG_OP = 'INSERT' THEN
        invoice := NEW.invoice_id;
    ELSE
        invoice := OLD.invoice_id;
    END IF;
    IF (SELECT status FROM forgebase._forgebase_billing_invoices WHERE id = invoice) <> 'draft' THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'lines of a finalized invoice are immutable';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END
$fb$;
CREATE TRIGGER _forgebase_billing_lines_frozen_update BEFORE UPDATE ON _forgebase_billing_invoice_lines
    FOR EACH ROW EXECUTE FUNCTION forgebase._forgebase_billing_lines_frozen();
CREATE TRIGGER _forgebase_billing_lines_frozen_delete BEFORE DELETE ON _forgebase_billing_invoice_lines
    FOR EACH ROW EXECUTE FUNCTION forgebase._forgebase_billing_lines_frozen();
CREATE TRIGGER _forgebase_billing_lines_frozen_insert BEFORE INSERT ON _forgebase_billing_invoice_lines
    FOR EACH ROW EXECUTE FUNCTION forgebase._forgebase_billing_lines_frozen();

-- Vector keyword index kept in sync with the items (0012_vector).
