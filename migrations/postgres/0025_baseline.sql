        DELETE FROM forgebase._forgebase_vector_fts WHERE rowid = OLD.key;
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') AND NEW.content IS NOT NULL THEN
        INSERT INTO forgebase._forgebase_vector_fts (rowid, content) VALUES (NEW.key, NEW.content);
    END IF;
    RETURN NULL;
END
