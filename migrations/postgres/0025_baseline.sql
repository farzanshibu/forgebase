-- PostgreSQL baseline (ADR-0028 §7.6): the system schema SQLite has after
-- migrations/system/0001 … 0025, written once by hand for PostgreSQL.
--
-- Applying this file records versions 1–25 (every SQLite version up to 25) in
-- forgebase._forgebase_migrations with this file's checksum, so a version
-- number means the same schema on both backends. From 0026 on every
-- migration is a pair: migrations/system/NNNN_x.sql and
-- migrations/postgres/NNNN_x.sql. NEVER EDIT THIS FILE once it has shipped.
--
-- The runner (crates/forgebase-migrations/src/postgres.rs) wraps it in one
-- transaction with `SET LOCAL search_path = forgebase, public` (and
-- `SET LOCAL ROLE forgebase_owner` where that role exists), so the unqualified
-- names below land in schema forgebase. Function bodies name their schema,
-- because they run with the caller's search_path.
--
-- Type mapping (ADR-0028 §7.4): INTEGER -> bigint; INTEGER PRIMARY KEY
-- [AUTOINCREMENT] -> bigint GENERATED BY DEFAULT AS IDENTITY; booleans
-- (INTEGER CHECK (x IN (0, 1))) -> smallint with the same check; REAL ->
-- double precision; TEXT -> text; TEXT CHECK (json_valid(x)) -> jsonb (a
-- json_type(x) = 'object' check becomes jsonb_typeof); TEXT COLLATE NOCASE ->
-- citext; BLOB -> bytea; STRICT and WITHOUT ROWID dropped; GLOB -> a regular
-- expression. Every foreign key is DEFERRABLE INITIALLY IMMEDIATE, so
-- TxMode::SchemaChange can defer them to COMMIT. RAISE(ABORT, msg) triggers
-- become PL/pgSQL functions raising SQLSTATE P0001 with the same message.
-- Tables the code orders by rowid get a `_rowid` identity column
-- (Dialect::row_order_col).
--
-- crates/forgebase-migrations/tests/schema_parity.rs migrates SQLite and
-- PostgreSQL to the head and fails on any difference.

CREATE SCHEMA IF NOT EXISTS forgebase;

-- NOCASE columns. citext and unaccent are trusted extensions: the database
-- owner may create them without being a superuser.
CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA forgebase;

-- Full text (FB-131 PG_FULLTEXT_SETUP): unaccent() is only STABLE, so the
-- generated tsvector columns call this IMMUTABLE wrapper. The body names the
-- extension's schema, so it works under any search_path.
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA forgebase;
DO $fb$
DECLARE
    s text;
BEGIN
    SELECT n.nspname INTO STRICT s
    FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
    WHERE e.extname = 'unaccent';
    EXECUTE format(
        'CREATE OR REPLACE FUNCTION forgebase._forgebase_unaccent(text) RETURNS text '
        'LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT '
        'AS $f$ SELECT %I.unaccent(%L::regdictionary, $1) $f$',
        s, quote_ident(s) || '.unaccent');
END
$fb$;

-- Raises the trigger's first argument as an error (SQLite's RAISE(ABORT, msg)).
CREATE FUNCTION forgebase._forgebase_abort() RETURNS trigger
LANGUAGE plpgsql AS $fb$
BEGIN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = TG_ARGV[0];
END
$fb$;

