-- Keyword side of hybrid search. SQLite: a contentless FTS5 table, rowid =
-- item key. PostgreSQL: a table with the text and a generated tsvector (the
-- same form PgDialect::fulltext_create uses) under a GIN index; the triggers
-- below keep it in sync as on SQLite.
CREATE TABLE _forgebase_vector_fts (
    rowid   bigint NOT NULL PRIMARY KEY,
    content text   NOT NULL,
    fts     tsvector GENERATED ALWAYS AS (to_tsvector('simple', forgebase._forgebase_unaccent(content))) STORED
);
CREATE INDEX _forgebase_vector_fts_gin ON _forgebase_vector_fts USING gin (fts);

