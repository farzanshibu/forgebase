ALTER TABLE _forgebase_alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE _forgebase_alert_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE _forgebase_alert_silences ENABLE ROW LEVEL SECURITY;
ALTER TABLE _forgebase_alert_notifiers ENABLE ROW LEVEL SECURITY;
ALTER TABLE _forgebase_alert_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE _forgebase_alert_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE _forgebase_slos ENABLE ROW LEVEL SECURITY;
ALTER TABLE _forgebase_slo_minutes ENABLE ROW LEVEL SECURITY;
