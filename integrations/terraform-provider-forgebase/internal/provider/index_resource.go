var (
	_           resource.Resource                = (*indexResource)(nil)
	_           resource.ResourceWithConfigure   = (*indexResource)(nil)
	_           resource.ResourceWithImportState = (*indexResource)(nil)
	indexNameRE                                  = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]{0,62}$`)
)

// NewIndexResource returns the forgebase_index resource.
func NewIndexResource() resource.Resource { return &indexResource{} }

type indexResource struct{ base }

type indexKeyModel struct {
	Path types.String `tfsdk:"path"`
	Desc types.Bool   `tfsdk:"desc"`
}

type indexModel struct {
	ID         types.String `tfsdk:"id"`
	Name       types.String `tfsdk:"name"`
	Collection types.String `tfsdk:"collection"`
	Keys       types.List   `tfsdk:"keys"`
	Unique     types.Bool   `tfsdk:"unique"`
	Kind       types.String `tfsdk:"kind"`
	Partial    types.String `tfsdk:"partial"`
}

type apiIndex struct {
	Name       string `json:"name"`
	Unique     bool   `json:"unique"`
	Definition *struct {
		Collection string `json:"collection"`
		Unique     *bool  `json:"unique"`
	} `json:"definition"`
}

func (r *indexResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_index"
}

func (r *indexResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.configureResource(req, resp)
}

func (r *indexResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	rr := []planmodifier.String{stringplanmodifier.RequiresReplace()}
	resp.Schema = schema.Schema{
		Description: "A manual index on a collection (B-tree, unique, partial, expression, JSON path, or full-text). " +
			"The server cannot alter an index, so every change replaces it. Indexes derived from field flags (`unique`) are managed by the collection.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{Computed: true, PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()}, Description: "The index name."},
			"name": schema.StringAttribute{
				Optional: true, Computed: true,
				Description:   "Index name (letters, digits, underscores; not starting with `auto_`, `sqlite_` or `pg_`). Generated by the server when omitted.",
				Validators:    []validator.String{stringvalidator.RegexMatches(indexNameRE, "must be 1-63 letters, digits or underscores, starting with a letter")},
				PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace(), stringplanmodifier.UseStateForUnknown()},
			},
			"collection": schema.StringAttribute{Required: true, Description: "Collection name.", PlanModifiers: rr},
			"keys": schema.ListNestedAttribute{
				Required:    true,
				Description: "Indexed keys in order. Each `path` is a field name, a JSON path or an expression in filter syntax.",
				Validators:  []validator.List{listvalidator.SizeAtLeast(1)},
				NestedObject: schema.NestedAttributeObject{Attributes: map[string]schema.Attribute{
					"path": schema.StringAttribute{Required: true, Description: "Field path in filter syntax."},
					"desc": schema.BoolAttribute{Optional: true, Computed: true, Default: booldefault.StaticBool(false), Description: "Descending order."},
				}},
				// Lists of objects cannot carry RequiresReplace per element; the whole attribute does.
				PlanModifiers: nil,
			},
			"unique": schema.BoolAttribute{
				Optional: true, Computed: true, Default: booldefault.StaticBool(false),
				Description: "Reject duplicate values.", PlanModifiers: []planmodifier.Bool{boolplanmodifier.RequiresReplace()},
			},
			"kind": schema.StringAttribute{
				Optional: true, Computed: true, Default: stringdefault.StaticString("btree"),
				Description:   "`btree` (default), `fulltext`, or `trigram` (PostgreSQL with `pg_trgm`).",
				Validators:    []validator.String{stringvalidator.OneOf("btree", "fulltext", "trigram")},
				PlanModifiers: rr,
			},
			"partial": schema.StringAttribute{Optional: true, Description: "Filter expression for a partial index.", PlanModifiers: rr},
		},
	}
}

// ModifyPlan forces replacement when the keys change (nested lists cannot carry RequiresReplace).
func (r *indexResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		return
	}
	var plan, state indexModel
	if resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...); resp.Diagnostics.HasError() {
		return
	}
	if resp.Diagnostics.Append(req.State.Get(ctx, &state)...); resp.Diagnostics.HasError() {
		return
	}
	if !plan.Keys.IsUnknown() && !plan.Keys.Equal(state.Keys) {
		resp.RequiresReplace = append(resp.RequiresReplace, path.Root("keys"))
	}
}

func (r *indexResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), req.ID)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("name"), req.ID)...)
}

func (r *indexResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan indexModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	var keys []indexKeyModel
	resp.Diagnostics.Append(plan.Keys.ElementsAs(ctx, &keys, false)...)
	if resp.Diagnostics.HasError() {
		return
	}
	apiKeys := make([]map[string]any, len(keys))
	for i, k := range keys {
		apiKeys[i] = map[string]any{"path": k.Path.ValueString(), "desc": k.Desc.ValueBool()}
	}
	body := map[string]any{
		"collection": plan.Collection.ValueString(), "keys": apiKeys,
		"unique": plan.Unique.ValueBool(), "kind": plan.Kind.ValueString(),
	}
	if !plan.Name.IsNull() && !plan.Name.IsUnknown() {
		body["name"] = plan.Name.ValueString()
	}
	if p := strPtr(plan.Partial); p != nil {
		body["partial"] = *p
	}
	var out apiIndex
	if err := r.c.Post(ctx, "/api/v1/indexes", body, &out); err != nil {
		addErr(&resp.Diagnostics, "Error creating index", err)
		return
	}
	plan.ID, plan.Name = types.StringValue(out.Name), types.StringValue(out.Name)
	plan.Unique = types.BoolValue(out.Unique)
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *indexResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state indexModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	var out apiIndex
	err := r.c.Get(ctx, "/api/v1/indexes/"+seg(state.ID.ValueString()), nil, &out)
	if removeIfGone(ctx, &resp.State, &resp.Diagnostics, "index", err) {
		return
	}
	state.ID, state.Name = types.StringValue(out.Name), types.StringValue(out.Name)
	state.Unique = types.BoolValue(out.Unique)
	if state.Collection.IsNull() && out.Definition != nil {
		state.Collection = types.StringValue(out.Definition.Collection)
	}
	if state.Keys.IsNull() {
		// Imported: the definition (when the server returns it) fills keys.
		var full struct {
			Definition *struct {
				Keys    []indexKeyJSON `json:"keys"`
				Kind    *string        `json:"kind"`
				Partial *string        `json:"partial"`
			} `json:"definition"`
		}
		if err := r.c.Get(ctx, "/api/v1/indexes/"+seg(out.Name), nil, &full); err == nil && full.Definition != nil {
			ks := make([]indexKeyModel, len(full.Definition.Keys))
			for i, k := range full.Definition.Keys {
				ks[i] = indexKeyModel{Path: types.StringValue(k.Path), Desc: types.BoolValue(k.Desc)}
			}
			state.Keys, _ = types.ListValueFrom(ctx, types.ObjectType{AttrTypes: map[string]attr.Type{"path": types.StringType, "desc": types.BoolType}}, ks)
			if full.Definition.Kind != nil {
				state.Kind = types.StringValue(*full.Definition.Kind)
			} else {
				state.Kind = types.StringValue("btree")
			}
			state.Partial = nullableString(full.Definition.Partial)
		}
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, state)...)
}

type indexKeyJSON struct {
	Path string `json:"path"`
	Desc bool   `json:"desc"`
}

func (r *indexResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	resp.Diagnostics.AddError("Index cannot be updated in place", "Every index attribute forces replacement; this is a provider bug.")
}

func (r *indexResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state indexModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.c.Delete(ctx, "/api/v1/indexes/"+seg(state.ID.ValueString()), nil); err != nil && !isGone(err) {
		addErr(&resp.Diagnostics, "Error dropping index", err)
	}
}
