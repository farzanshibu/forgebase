//! The `Database` facade on both backends (FB-131, ADR-0028 §7).
//!
//! SQLite tests always run. PostgreSQL tests run when an engine or server is
//! configured (`FORGEBASE_PG_ENGINE_DIR`, `FORGEBASE_TEST_PG_ENGINE` or
//! `FORGEBASE_TEST_PG_URL`, see `forgebase_db::testing`) and skip otherwise.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::sync::Arc;
use std::time::Duration;

use forgebase_core::ErrorCode;
use forgebase_db::testing::{self, TestDb};
use forgebase_db::{
    Backend, BackendKind, ConstraintKind, Database, DbError, DbTarget, PG_FULLTEXT_SETUP, Statement, TxMode, Value,
};

/// A PostgreSQL test database, or `None` (test skipped) without an engine.
async fn pg() -> Option<TestDb> {
    let db = testing::postgres_test_db().await;
    if db.is_none() {
        eprintln!("skipped: no PostgreSQL engine configured (set FORGEBASE_PG_ENGINE_DIR)");
    }
    db
}

async fn exec(db: &Database, sql: &str, params: Vec<Value>) -> u64 {
    let mut tx = db.begin(TxMode::Normal).await.unwrap();
    let done = tx.execute(&Statement::new(sql, params)).await.unwrap();
    tx.commit().await.unwrap();
    done.rows_affected
}

async fn ddl(db: &Database, sql: &str) {
    let mut tx = db.begin(TxMode::SchemaChange).await.unwrap();
    tx.execute(&Statement::raw(sql)).await.unwrap();
    tx.commit().await.unwrap();
}

async fn rows(db: &Database, sql: &str, params: Vec<Value>) -> Vec<Vec<Value>> {
    db.fetch_all(&Statement::new(sql, params)).await.unwrap().rows
}

