#[tokio::test]
async fn postgres_dialect_methods_run_on_postgres() {
    let Some(db) = pg().await else { return };
    let d = db.dialect();
    ddl(&db, "CREATE TABLE t (k text PRIMARY KEY, v text, n bigint, h jsonb)").await;
    let ins = d.insert_ignore("t", "k, v, n", "VALUES (?1, ?2, ?3)");
    exec(&db, &ins, vec!["a".into(), "Xylo".into(), 1.into()]).await;
    assert_eq!(exec(&db, &ins, vec!["a".into(), "y".into(), 2.into()]).await, 0);
    let up = d.upsert("t", &["k", "v", "n"], &["k"], "VALUES (?1, ?2, ?3)");
    exec(&db, &up, vec!["b".into(), "B".into(), Value::Null]).await;
    exec(&db, &up, vec!["c".into(), "C".into(), 3.into()]).await;
    // NULLs sort first ascending, as on SQLite.
    let r = rows(
        &db,
        &format!("SELECT k FROM t ORDER BY n {}", d.order_nulls(false)),
        vec![],
    )
    .await;
    assert_eq!(r[0][0], Value::Text("b".into()));
    let r = rows(
        &db,
        &format!("SELECT k FROM t ORDER BY n {}", d.order_nulls(true)),
        vec![],
    )
    .await;
    assert_eq!(r[2][0], Value::Text("b".into()));
    let r = rows(
        &db,
        &format!("SELECT k FROM t WHERE {} ORDER BY k", d.in_json_list("k", "?1")),
        vec![r#"["a","c","z"]"#.into()],
    )
    .await;
    assert_eq!(r.len(), 2);
    let r = rows(
        &db,
        &format!("SELECT k FROM t WHERE {}", d.like_ci("v", "?1")),
        vec!["xY%".into()],
    )
    .await;
    assert_eq!(r, vec![vec![Value::Text("a".into())]]);
    let r = rows(
        &db,
        &format!(
            "SELECT {}, {}, {}",
            d.json_array_append("'[1]'", "?1"),
            d.json_set_last(r#"'[{"a":1},{"a":2}]'"#, "a", "?2"),
            d.now_epoch()
        ),
        vec![2.into(), "z".into()],
    )
    .await;
    assert_eq!(r[0][0], Value::Text("[1,2]".into()));
    assert_eq!(r[0][1], Value::Text(r#"[{"a":1},{"a":"z"}]"#.into()));
    assert!(matches!(r[0][2], Value::Integer(t) if t > 1_700_000_000));
    let agg = rows(
        &db,
        &format!("SELECT {} FROM t WHERE false", d.json_array_agg("k")),
        vec![],
    )
    .await;
    assert_eq!(agg[0][0], Value::Text("[]".into()));
    let path = [forgebase_db::JsonPathSeg::key("a").unwrap()];
    let r = rows(
        &db,
        &format!("SELECT {}", d.json_extract("'{\"a\": \"x\"}'::jsonb", &path)),
        vec![],
    )
    .await;
    assert_eq!(r[0][0], Value::Text("x".into()));
    // Catalog introspection returns SQLite's column names.
    let cols = db.fetch_all(&d.introspect_columns("t")).await.unwrap();
    let name = cols.column("name").unwrap();
    let pk = cols.column("pk").unwrap();
    assert_eq!(
        cols.rows.iter().map(|r| r[name].clone()).collect::<Vec<_>>(),
        vec![
            Value::Text("k".into()),
            Value::Text("v".into()),
            Value::Text("n".into()),
            Value::Text("h".into())
        ]
    );
    assert_eq!(cols.rows[0][pk], Value::Integer(1));
    assert_eq!(cols.rows[1][pk], Value::Integer(0));
    let idx = db.fetch_all(&d.introspect_indexes("t")).await.unwrap();
    assert_eq!(idx.rows[0][idx.column("origin").unwrap()], Value::Text("pk".into()));
    assert_eq!(idx.rows[0][idx.column("unique").unwrap()], Value::Integer(1));
    let tables = db.fetch_all(&d.introspect_tables()).await.unwrap();
    assert!(tables.rows.iter().any(|r| r[0] == Value::Text("t".into())));
    let size = db.fetch_all(&d.object_size("t")).await.unwrap();
    assert!(matches!(size.scalar(), Some(Value::Integer(n)) if *n > 0));
    exec(&db, "ANALYZE t", vec![]).await;
    let stats = db.fetch_all(&d.index_stats("t_pkey")).await.unwrap();
    assert_eq!(stats.len(), 1);
    // Full text: tsvector column + GIN, lower rank is better.
    let mut tx = db.begin(TxMode::SchemaChange).await.unwrap();
    for sql in PG_FULLTEXT_SETUP {
        tx.execute(&Statement::raw(*sql)).await.unwrap();
    }
    for sql in d.fulltext_create("t", "_forgebase_fts_t", &["v".into(), "k".into()], &[]) {
        tx.execute(&Statement::raw(sql)).await.unwrap();
    }
    tx.commit().await.unwrap();
    exec(&db, "UPDATE t SET v = 'café crème' WHERE k = 'c'", vec![]).await;
    let r = rows(
        &db,
        &format!(
            "SELECT t.k, {} FROM t WHERE {} ORDER BY 2",
            d.fulltext_rank("t", "_forgebase_fts_t", "?1"),
            d.fulltext_match("t", "_forgebase_fts_t", "?1")
        ),
        vec!["cafe".into()],
    )
    .await;
    assert_eq!(r.len(), 1, "unaccented match: {r:?}");
    assert_eq!(r[0][0], Value::Text("c".into()));
    for sql in d.fulltext_drop("t", "_forgebase_fts_t") {
        ddl(&db, &sql).await;
    }
    // Long derived names fit PostgreSQL's 63 bytes and stay distinct.
    let long = format!("auto_{}", "x".repeat(70));
    ddl(
        &db,
        &format!("CREATE INDEX {} ON t (v)", d.quote_ident(&d.fit_ident(&long))),
    )
    .await;
    let names = rows(&db, "SELECT indexname FROM pg_indexes WHERE tablename = 't'", vec![]).await;
    assert!(names.iter().any(|r| r[0] == Value::Text(d.fit_ident(&long))));
}

#[tokio::test]
async fn postgres_seams_for_replicas_and_shards() {
    let Some(a) = pg().await else { return };
    let Some(b) = pg_with_schema().await else { return };
    // Commit LSNs (read-your-writes on replicas): set by commits, never going back.
    assert_eq!(a.last_commit_lsn(), None, "no commit yet");
    ddl(&a, PG_SCHEMA).await;
    a.meta_set("k", "1").await.unwrap();
    let first = a.last_commit_lsn().expect("a commit records its WAL position");
    a.meta_set("k", "2").await.unwrap();
    let second = a.last_commit_lsn().unwrap();
    assert!(second > first, "{first} then {second}");
    let now = a.current_wal_lsn().await.unwrap().unwrap();
    assert!(now >= second);
    assert_eq!(now.to_string().parse::<forgebase_db::Lsn>().unwrap(), now);
    // One Database per target, cheap to clone, no shared state: a shard map
    // can hold one per shard.
    let shards = [a.database().clone(), b.database().clone()];
    shards[1].meta_set("k", "shard-b").await.unwrap();
    assert_eq!(shards[0].meta_get("k").await.unwrap().as_deref(), Some("2"));
    assert_eq!(shards[1].meta_get("k").await.unwrap().as_deref(), Some("shard-b"));
    assert_eq!(b.last_commit_lsn().map(|l| l > Default::default()), Some(true));
    // SQLite has no LSN.
    let sqlite = testing::test_backend_of(BackendKind::Sqlite).await;
    sqlite.meta_set("k", "v").await.unwrap();
    assert_eq!(sqlite.last_commit_lsn(), None);
    assert_eq!(sqlite.current_wal_lsn().await.unwrap(), None);
}

/// PostgreSQL's `text` cannot hold U+0000: both engines refuse such a value
/// before running the statement, with the same error (no half-portable data).
#[tokio::test]
async fn a_nul_character_in_text_is_refused_alike_on_both_engines() {
    let test = forgebase_db::testing::test_backend().await;
    let db: &Database = &test;
    ddl(db, "CREATE TABLE nul_t (v text)").await;
    let mut tx = db.begin(TxMode::Normal).await.unwrap();
    let e = tx
        .execute(&Statement::new(
            "INSERT INTO nul_t (v) VALUES (?1)",
            vec![Value::Text("a\0b".into())],
        ))
        .await
        .unwrap_err();
    assert_eq!(e.code(), "invalid_statement", "{e}");
    assert!(e.to_string().contains("U+0000"), "{e}");
    tx.rollback().await.unwrap();
    let e = db
        .fetch_all(&Statement::new("SELECT ?1 AS v", vec![Value::Text("\0".into())]))
        .await
        .unwrap_err();
    assert_eq!(e.code(), "invalid_statement", "{e}");
}
