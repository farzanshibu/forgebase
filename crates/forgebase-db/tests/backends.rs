#[tokio::test]
async fn sqlite_dialect_methods_are_valid_sqlite() {
    let db = testing::test_backend_of(BackendKind::Sqlite).await;
    let d = db.dialect();
    ddl(&db, "CREATE TABLE t (k TEXT PRIMARY KEY, v TEXT, n INTEGER)").await;
    exec(
        &db,
        &d.insert_ignore("t", "k, v, n", "VALUES (?1, ?2, ?3)"),
        vec!["a".into(), "x".into(), 1.into()],
    )
    .await;
    exec(
        &db,
        &d.insert_ignore("t", "k, v, n", "VALUES (?1, ?2, ?3)"),
        vec!["a".into(), "y".into(), 2.into()],
    )
    .await;
    exec(
        &db,
        &d.upsert("t", &["k", "v", "n"], &["k"], "VALUES (?1, ?2, ?3)"),
        vec!["b".into(), "B".into(), Value::Null],
    )
    .await;
    exec(
        &db,
        &d.upsert("t", &["k", "v", "n"], &["k"], "VALUES (?1, ?2, ?3)"),
        vec!["b".into(), "B2".into(), 5.into()],
    )
    .await;
    let r = rows(
        &db,
        &format!(
            "SELECT k, v FROM t WHERE {} ORDER BY n {}",
            d.in_json_list("k", "?1"),
            d.order_nulls(false)
        ),
        vec![r#"["a","b","z"]"#.into()],
    )
    .await;
    assert_eq!(r.len(), 2);
    assert_eq!(r[0][1], Value::Text("x".into()), "insert_ignore kept the first row");
    let r = rows(
        &db,
        &format!("SELECT k FROM t WHERE {}", d.like_ci("v", "?1")),
        vec!["b%".into()],
    )
    .await;
    assert_eq!(r, vec![vec![Value::Text("b".into())]]);
    let r = rows(
        &db,
        &format!(
            "SELECT {}, {}, {}",
            d.json_array_append("'[1]'", "?1"),
            d.json_set_last(r#"'[{"a":1},{"a":2}]'"#, "a", "?2"),
            d.now_epoch()
        ),
        vec![2.into(), 9.into()],
    )
    .await;
    assert_eq!(r[0][0], Value::Text("[1,2]".into()));
    assert_eq!(r[0][1], Value::Text(r#"[{"a":1},{"a":9}]"#.into()));
    let agg = rows(&db, &format!("SELECT {} FROM t", d.json_array_agg("k")), vec![]).await;
    assert!(matches!(&agg[0][0], Value::Text(s) if s.starts_with('[')));
    let cols = db.fetch_all(&d.introspect_columns("t")).await.unwrap();
    assert!(cols.column("name").is_some() && cols.column("pk").is_some());
    assert_eq!(cols.len(), 3);
    let tables = db.fetch_all(&d.introspect_tables()).await.unwrap();
    assert!(tables.rows.iter().any(|r| r[0] == Value::Text("t".into())));
}

#[tokio::test]
async fn postgres_open_read_write_and_types() {
    let Some(db) = pg_with_schema().await else { return };
    assert_eq!(db.kind(), BackendKind::Postgres);
    assert_eq!(db.dialect().name(), "postgres");
    let sql = "INSERT INTO items (name, qty, price, amount, data, flag, blob, at, uid)
               VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, ?9)";
    let n = exec(
        &db,
        sql,
        vec![
            "widget".into(),
            7.into(),
            2.5.into(),
            Value::Text("12.50".into()),
            Value::Text(r#"{"b": [1, 2], "a": "x y"}"#.into()),
            true.into(),
            Value::Blob(vec![0, 1, 255]),
            "2026-11-11T01:15:00.123Z".into(),
            "6f1c1e9a-3f0e-4c3b-9a55-0d7c1f5e0a11".into(),
        ],
    )
    .await;
    assert_eq!(n, 1);
    let r = db
        .fetch_all(&Statement::new(
            "SELECT id, name, qty, price, amount, data, flag, blob, at, uid, created_at > 0 AS recent FROM items WHERE name = ?1",
            vec!["widget".into()],
        ))
        .await
        .unwrap();
    assert_eq!(r.columns[1], "name");
    let row = &r.rows[0];
    assert_eq!(row[0], Value::Integer(1));
    assert_eq!(row[2], Value::Integer(7));
    assert_eq!(row[3], Value::Real(2.5));
    assert_eq!(row[4], Value::Real(12.5));
    // jsonb comes back as compact JSON text (keys in jsonb order).
    let Value::Text(json) = &row[5] else {
        panic!("json is text")
    };
    let parsed: serde_json::Value = serde_json::from_str(json).unwrap();
    assert_eq!(parsed, serde_json::json!({"a": "x y", "b": [1, 2]}));
    assert!(!json.contains(": "), "compact: {json}");
    assert_eq!(row[6], Value::Integer(1));
    assert_eq!(row[7], Value::Blob(vec![0, 1, 255]));
    assert_eq!(row[8], Value::Text("2026-11-11T01:15:00.123Z".into()));
    assert_eq!(row[9], Value::Text("6f1c1e9a-3f0e-4c3b-9a55-0d7c1f5e0a11".into()));
    assert_eq!(row[10], Value::Integer(1));

    // An empty result still names its columns.
    let empty = db
        .fetch_all(&Statement::new(
            "SELECT id, name FROM items WHERE qty > ?1",
            vec![100.into()],
        ))
        .await
        .unwrap();
    assert!(empty.is_empty());
    assert_eq!(empty.columns, vec!["id", "name"]);

    // Lossless conversions are accepted; others are refused, never cast.
    let r = rows(&db, "SELECT name FROM items WHERE qty = ?1", vec!["7".into()]).await;
    assert_eq!(r.len(), 1);
    let err = db
        .fetch_all(&Statement::new(
            "SELECT name FROM items WHERE qty = ?1",
            vec!["seven".into()],
        ))
        .await
        .unwrap_err();
    assert_eq!(err.code(), "invalid_statement", "{err}");
    assert!(err.to_string().contains("$1"), "{err}");
    let err = db
        .fetch_all(&Statement::new(
            "SELECT name FROM items WHERE flag = ?1",
            vec![2.into()],
        ))
        .await;
    assert!(
        err.is_ok(),
        "smallint takes 2 even though the CHECK would refuse it on insert"
    );

    // System metadata and the instance identity.
    let instance = db.ensure_instance().await.unwrap();
    assert_eq!(instance.instance_id.len(), 36);
    assert_eq!(db.ensure_instance().await.unwrap(), instance);
    db.meta_set("greeting", "hello").await.unwrap();
    db.meta_set("greeting", "hello again").await.unwrap();
    assert_eq!(db.meta_get("greeting").await.unwrap().as_deref(), Some("hello again"));
    assert_eq!(db.meta_all().await.unwrap().len(), 3);
    assert!(db.meta_delete("greeting").await.unwrap());
    assert!(!db.meta_delete("greeting").await.unwrap());

    // Reopen through the options: data survives.
    db.close().await;
    let again = Database::open(db.options().create_if_missing(false)).await.unwrap();
    assert_eq!(again.ensure_instance().await.unwrap(), instance);
    again.close().await;
}

#[tokio::test]
async fn postgres_placeholder_edge_cases() {
    let Some(db) = pg().await else { return };
    // ?N inside strings, comments, dollar quotes and quoted identifiers stays text.
    let r = rows(
        &db,
        "SELECT ?1::bigint AS a, '?2 and ?' AS b /* ?3 */, ?3 AS \"c?\", $$ ?1 $$ AS d -- ?9\n, E'\\' ?1' AS e",
        vec![1.into(), "unused".into(), "three".into()],
    )
    .await;
    assert_eq!(
        r[0],
        vec![
            Value::Integer(1),
            Value::Text("?2 and ?".into()),
            Value::Text("three".into()),
            Value::Text(" ?1 ".into()),
            Value::Text("' ?1".into()),
        ]
    );
    // Bare ? numbering follows SQLite.
    let r = rows(&db, "SELECT ?2, ?, ?1", vec!["a".into(), "b".into(), "c".into()]).await;
    assert_eq!(
        r[0],
        vec![
            Value::Text("b".into()),
            Value::Text("c".into()),
            Value::Text("a".into())
        ]
    );
    // Missing parameters bind NULL, as SQLite does.
    let r = rows(&db, "SELECT ?1 IS NULL, ?2", vec![Value::Null]).await;
    assert_eq!(r[0], vec![Value::Integer(1), Value::Null]);
    // The same statement with different types each time hits the statement cache.
    for i in 0..3 {
        let r = rows(&db, "SELECT ?1 + 1", vec![Value::Integer(i)]).await;
        assert_eq!(r[0][0], Value::Integer(i + 1));
    }
    // Array parameters take a JSON array.
    let r = rows(&db, "SELECT 'b' = ANY (?1::text[])", vec![r#"["a","b"]"#.into()]).await;
    assert_eq!(r[0][0], Value::Integer(1));
    // Out-of-range numbers are refused before anything is sent.
    let err = db.fetch_all(&Statement::new("SELECT ?0", vec![])).await.unwrap_err();
    assert_eq!(err.code(), "invalid_statement");
}

#[tokio::test]
async fn postgres_transactions_commit_rollback_and_drop() {
    let Some(db) = pg_with_schema().await else { return };
    let count = |db: Database| async move { rows(&db, "SELECT count(*) FROM items", vec![]).await[0][0].clone() };
    let insert = |name: &str| Statement::new("INSERT INTO items (name) VALUES (?1)", vec![name.into()]);

    let mut tx = db.begin(TxMode::Normal).await.unwrap();
    tx.execute(&insert("a")).await.unwrap();
    // Read-your-writes inside the transaction, invisible outside.
    let inside = tx
        .fetch_all(&Statement::raw("SELECT count(*) FROM items"))
        .await
        .unwrap();
    assert_eq!(inside.scalar(), Some(&Value::Integer(1)));
    assert_eq!(count(db.database().clone()).await, Value::Integer(0));
    tx.rollback().await.unwrap();
    assert_eq!(count(db.database().clone()).await, Value::Integer(0));

    // Dropped without commit: rolled back, and the writer is usable again.
    {
        let mut tx = db.begin(TxMode::Normal).await.unwrap();
        tx.execute(&insert("dropped")).await.unwrap();
    }
    let mut tx = tokio::time::timeout(Duration::from_secs(10), db.begin(TxMode::Normal))
        .await
        .expect("the writer comes back after a dropped transaction")
        .unwrap();
    tx.execute(&insert("b")).await.unwrap();
    tx.commit().await.unwrap();
    assert_eq!(
        rows(&db, "SELECT name FROM items", vec![]).await,
        vec![vec![Value::Text("b".into())]]
    );

    // RETURNING through fetch_all, and the dialect's returning_id.
    let mut tx = db.begin(TxMode::Normal).await.unwrap();
    let ret = tx
        .fetch_all(&Statement::new(
            format!(
                "INSERT INTO items (name) VALUES (?1) {}",
                db.dialect().returning_id("id")
            ),
            vec!["c".into()],
        ))
        .await
        .unwrap();
    assert!(matches!(ret.scalar(), Some(Value::Integer(id)) if *id > 1));
    tx.commit().await.unwrap();

    // A failed statement aborts a PostgreSQL transaction: commit reports it
    // and nothing of the transaction is kept.
    let mut tx = db.begin(TxMode::Normal).await.unwrap();
    tx.execute(&insert("d")).await.unwrap();
    let dup = tx.execute(&insert("b")).await.unwrap_err();
    assert!(
        matches!(
            dup,
            DbError::Constraint {
                kind: ConstraintKind::Unique,
                ..
            }
        ),
        "{dup}"
    );
    let err = tx.commit().await.unwrap_err();
    assert_eq!(err.code(), "invalid_statement");
    assert!(
        rows(&db, "SELECT 1 FROM items WHERE name = 'd'", vec![])
            .await
            .is_empty()
    );

    // Schema-change transactions defer foreign keys to COMMIT.
    let mut tx = db.begin(TxMode::SchemaChange).await.unwrap();
    tx.execute(&Statement::raw("INSERT INTO children VALUES ('c1', 'p1')"))
        .await
        .unwrap();
    tx.execute(&Statement::raw("INSERT INTO parents VALUES ('p1')"))
        .await
        .unwrap();
    tx.commit().await.unwrap();
    let mut tx = db.begin(TxMode::SchemaChange).await.unwrap();
    tx.execute(&Statement::raw("INSERT INTO children VALUES ('c2', 'missing')"))
        .await
        .unwrap();
    let err = tx.commit().await.unwrap_err();
    assert!(
        matches!(
            err,
            DbError::Constraint {
                kind: ConstraintKind::ForeignKey,
                ..
            }
        ),
        "{err}"
    );
    // In a normal transaction the same row fails at once.
    let mut tx = db.begin(TxMode::Normal).await.unwrap();
    let err = tx
        .execute(&Statement::raw("INSERT INTO children VALUES ('c3', 'missing')"))
        .await
        .unwrap_err();
    assert_eq!(err.code(), "foreign_key_violation");
    drop(tx);
    assert_eq!(db.foreign_key_violations().await.unwrap(), 0);
}

#[tokio::test]
async fn postgres_single_writer_keeps_sequence_order_equal_to_commit_order() {
    let Some(db) = pg().await else { return };
    ddl(
        &db,
        "CREATE TABLE seqlog (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, worker bigint)",
    )
    .await;
    assert_eq!(db.pool_stats().writer.max, 1, "exactly one writer connection");

    // While one transaction is open, a second writer waits.
    let tx1 = db.begin(TxMode::Normal).await.unwrap();
    assert!(
        tokio::time::timeout(Duration::from_millis(300), db.begin(TxMode::Normal))
            .await
            .is_err(),
        "a second writer must queue behind the first"
    );
    tx1.commit().await.unwrap();

    let done = Arc::new(std::sync::atomic::AtomicBool::new(false));
    let writers: Vec<_> = (0..6)
        .map(|w| {
            let db = db.database().clone();
            tokio::spawn(async move {
                for _ in 0..20 {
                    let mut tx = db.begin(TxMode::Normal).await.unwrap();
                    tx.execute(&Statement::new(
                        "INSERT INTO seqlog (worker) VALUES (?1)",
                        vec![Value::Integer(w)],
                    ))
                    .await
                    .unwrap();
                    // Hold the transaction open across an await point.
                    tokio::time::sleep(Duration::from_millis(1)).await;
                    tx.commit().await.unwrap();
                }
            })
        })
        .collect();
    let reader = {
        let (db, done) = (db.database().clone(), Arc::clone(&done));
        tokio::spawn(async move {
            let mut checks = 0;
            while !done.load(std::sync::atomic::Ordering::Acquire) || checks == 0 {
                let ids = rows(&db, "SELECT id FROM seqlog ORDER BY id", vec![]).await;
                // Commit order == sequence order: a reader never sees a gap.
                for (i, r) in ids.iter().enumerate() {
                    assert_eq!(r[0], Value::Integer(i as i64 + 1), "gap in committed ids: {ids:?}");
                }
                checks += 1;
            }
            checks
        })
    };
    for w in writers {
        w.await.unwrap();
    }
    done.store(true, std::sync::atomic::Ordering::Release);
    assert!(reader.await.unwrap() > 0);
    assert_eq!(
        rows(&db, "SELECT count(*) FROM seqlog", vec![]).await[0][0],
        Value::Integer(120)
    );
}

#[tokio::test]
async fn postgres_reads_cannot_write_or_change_the_session() {
    let Some(db) = pg_with_schema().await else { return };
    let err = db
        .fetch_all(&Statement::new(
            "INSERT INTO items (name) VALUES (?1)",
            vec!["x".into()],
        ))
        .await
        .unwrap_err();
    assert!(matches!(err, DbError::ReadOnly(_)), "{err}");
    let err = db
        .fetch_all(&Statement::raw(
            "WITH d AS (DELETE FROM items RETURNING id) SELECT count(*) FROM d",
        ))
        .await
        .unwrap_err();
    assert_eq!(err.code(), "statement_not_read_only");
    // Session settings changed by a read are rolled back with it.
    for _ in 0..8 {
        rows(&db, "SELECT set_config('forgebase_test.x', 'leak', false)", vec![]).await;
    }
    for _ in 0..8 {
        let r = rows(&db, "SELECT current_setting('forgebase_test.x', true)", vec![]).await;
        assert_ne!(r[0][0], Value::Text("leak".into()));
    }
    // Write classification (explain-based for queries).
    let writes = |sql: &'static str| {
        let db = db.database().clone();
        async move { db.statement_writes(&Statement::raw(sql)).await.unwrap() }
    };
    assert!(!writes("SELECT * FROM items").await);
    assert!(!writes("  /* hi */ (SELECT 1)").await);
    assert!(writes("WITH d AS (DELETE FROM items RETURNING id) SELECT * FROM d").await);
    assert!(writes("SELECT * FROM items FOR UPDATE").await);
    assert!(writes("INSERT INTO items (name) VALUES ('z')").await);
    assert!(writes("CREATE TABLE z (a int)").await);
    assert!(!writes("SHOW server_version").await);
}

#[tokio::test]
async fn postgres_errors_map_to_db_errors() {
    let Some(db) = pg_with_schema().await else { return };
    exec(
        &db,
        "INSERT INTO items (name, flag) VALUES (?1, ?2)",
        vec!["a".into(), 0.into()],
    )
    .await;
    let run = |sql: &'static str| {
        let db = db.database().clone();
        async move {
            let mut tx = db.begin(TxMode::Normal).await.unwrap();
            tx.execute(&Statement::raw(sql)).await.unwrap_err()
        }
    };
    let e = run("INSERT INTO items (name) VALUES ('a')").await;
    match &e {
        DbError::Constraint {
            kind: ConstraintKind::Unique,
            message,
        } => assert_eq!(message, "UNIQUE constraint failed: items.name"),
        other => panic!("{other}"),
    }
    let e = run("INSERT INTO items (name) VALUES (NULL)").await;
    assert!(
        matches!(&e, DbError::Constraint { kind: ConstraintKind::NotNull, message } if message == "NOT NULL constraint failed: items.name"),
        "{e}"
    );
    let e = run("INSERT INTO items (name, flag) VALUES ('b', 5)").await;
    assert_eq!(e.code(), "check_violation", "{e}");
    let e = run("SELEC 1").await;
    assert_eq!(e.code(), "invalid_statement");
    let e = run("SELECT * FROM no_such_table").await;
    assert_eq!(e.code(), "invalid_statement");
    // A trigger's RAISE EXCEPTION (the immutability triggers) is a CHECK failure.
    ddl(
        &db,
        "CREATE FUNCTION no_update() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'items are immutable' USING ERRCODE = 'P0001'; END $$;
         CREATE TRIGGER items_immutable BEFORE UPDATE ON items FOR EACH ROW EXECUTE FUNCTION no_update();",
    )
    .await;
    let e = run("UPDATE items SET qty = 1").await;
    assert!(
        matches!(&e, DbError::Constraint { kind: ConstraintKind::Check, message } if message == "items are immutable"),
        "{e}"
    );
    // A server that is not there is unavailable, not a statement error.
    let gone = Database::open(db.options().with_target(DbTarget::postgres(
        "postgres://nobody@127.0.0.1:1/x?connect_timeout=2",
        false,
    )))
    .await
    .unwrap_err();
    assert_eq!(gone.code(), "database_unavailable", "{gone}");
}

