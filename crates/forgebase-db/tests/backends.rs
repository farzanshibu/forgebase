#[tokio::test]
async fn postgres_schema_changes_refresh_cached_statements() {
    let Some(db) = pg().await else { return };
    ddl(&db, "CREATE TABLE s (a bigint)").await;
    exec(&db, "INSERT INTO s VALUES (?1)", vec![1.into()]).await;
    // Warm every reader's statement cache with SELECT *.
    for _ in 0..12 {
        assert_eq!(rows(&db, "SELECT * FROM s", vec![]).await[0].len(), 1);
    }
    let mut tx = db.begin(TxMode::Normal).await.unwrap();
    tx.execute(&Statement::raw("ALTER TABLE s ADD COLUMN b text DEFAULT 'x'"))
        .await
        .unwrap();
    // Inside the transaction the writer already sees the new column.
    let inside = tx.fetch_all(&Statement::new("SELECT * FROM s", vec![])).await.unwrap();
    assert_eq!(inside.columns, vec!["a", "b"]);
    tx.commit().await.unwrap();
    for _ in 0..12 {
        let r = db.fetch_all(&Statement::new("SELECT * FROM s", vec![])).await.unwrap();
        assert_eq!(r.columns, vec!["a", "b"]);
        assert_eq!(r.rows[0][1], Value::Text("x".into()));
    }
}

